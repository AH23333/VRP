"""D10（构想v10）：strangler scaffold 生成器——propose 的自然延伸。

propose 已给分区草案（.vrp/proposals/structure-proposal.json），本命令
从"提议"走到"可执行的迁移计划"（Martin Fowler strangler-fig 模式权威；
hygen/plop/cookiecutter 模板引擎形态参照——**造**：模板渲染纯 stdlib
string.Template，shim 生成 Python 先行，21 引擎 import 语义后批）。

三件产物（落 `<repo>/.vrp/scaffold/`，staging 区——采纳=人移文件）：
1. **模块骨架**：`<safe_id>/__init__.py`——docstring 带 [PROPOSED]
   name/responsibility（proposal 单源直引）+ 迁移 TODO（成员符号
   name/label/来源文件，facts.db fid join）；
2. **re-export shim 模板**：`shims/<old>__to__<safe_id>.py`——旧文件→
   新模块的 re-export 行（Function/Class 模块级可导出面；Method 随
   Class 走不可独立导出——诚实排除）+ strangler 说明头；同旧文件多
   模块认领=每对一 shim；
3. **MIGRATION.md**：迁移序=Fowler 先边缘后核心——按跨模块边数
   （SLICE_EDGE_TYPES 单一权威，提案 fid 集受限计数）升序，边缘
   （跨界边最少）先迁，平局 module_id 字典序；逐模块检查单。

红线：不碰用户源文件（shim 是模板不覆写原文件——采纳动作归人）；
facts.db 只读；同 proposal+facts.db → 字节级同产物（无时间戳全排序）。
"""

from __future__ import annotations

import json
import re
import sqlite3
from pathlib import Path
from string import Template

from . import dbpath
from .curate import SLICE_EDGE_TYPES

PROPOSAL_DEFAULT_PATH = Path(".vrp") / "proposals" / "structure-proposal.json"
SCAFFOLD_DEFAULT_DIR = Path(".vrp") / "scaffold"
# 模块级可导出面（shim re-export 候选）；Method 随 Class 走不可独立导出
SHIMMABLE_LABELS = ("Function", "Class")

_SAFE = re.compile(r"[^a-zA-Z0-9_]+")

_SKELETON = Template('''"""$name

$responsibility

Generated by `vrp scaffold` (D10 strangler scaffold) - [PROPOSED] draft,
review before adoption. Migration TODO (move these symbols here, from
their current files; see ../MIGRATION.md for order):
$todo
"""
''')

_SHIM = Template('''# strangler shim (generated by `vrp scaffold`, D10)
# Append these re-exports to the original file after moving the symbols to
# `$target_pkg` so existing callers keep working; delete the lines once all
# callers import from the new module directly (Fowler strangler-fig).
from $target_pkg import $imports
''')


def _safe_id(module_id: str) -> str:
    """module_id（可能含 `/`、`(root)`）→ Python 包名安全形；deterministic。"""
    name = _SAFE.sub("_", module_id.replace("\\", "/"))
    name = name.strip("_") or "module"
    return name


def _connect_ro(repo: Path) -> sqlite3.Connection:
    db = Path(repo) / ".vrp" / "facts.db"
    if not db.exists():
        raise SystemExit(f"facts.db missing - run 'vrp run' first: {db}")
    return dbpath.ro_connect(db)


def run_scaffold(
    repo: Path,
    proposal: Path | None = None,
    out: Path | None = None,
) -> dict:
    """`vrp scaffold` 入口：proposal 缺失诚实退出（先跑 propose）。"""
    repo = Path(repo)
    proposal_path = Path(proposal) if proposal else repo / PROPOSAL_DEFAULT_PATH
    if not proposal_path.exists():
        raise SystemExit(
            f"proposal missing - run 'vrp propose' first: {proposal_path}"
        )
    try:
        payload = json.loads(proposal_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise SystemExit(f"cannot load proposal {proposal_path}: {exc}")
    if not isinstance(payload, dict):
        raise SystemExit(f"proposal top level must be a JSON object: {proposal_path}")
    modules = payload.get("modules")
    if not isinstance(modules, list) or not modules:
        raise SystemExit(f"proposal has no modules: {proposal_path}")
    out_dir = Path(out) if out else repo / SCAFFOLD_DEFAULT_DIR
    con = _connect_ro(repo)
    try:
        return _build(repo, con, modules, proposal_path, out_dir)
    finally:
        con.close()


def _build(
    repo: Path,
    con: sqlite3.Connection,
    modules: list[dict],
    proposal_path: Path,
    out_dir: Path,
) -> dict:
    # fid → (module_id) 映射 + 成员元数据 join（name/label/file_path）
    fid_mod: dict[str, str] = {}
    for m in modules:
        for fid in m.get("symbol_fids", []):
            fid_mod[fid] = m["module_id"]
    marks = ",".join("?" * len(fid_mod)) or "''"
    meta: dict[str, tuple[str, str, str]] = {}
    if fid_mod:
        for fid, name, label, fp in con.execute(
            f"SELECT fid, name, label, file_path FROM symbols WHERE fid IN ({marks})",
            sorted(fid_mod),
        ):
            meta[fid] = (name or "", label or "", fp or "")
    # 跨模块边计数（迁移序信号：边缘=跨界边少先迁，Fowler 先边缘后核心）
    cross: dict[str, int] = {m["module_id"]: 0 for m in modules}
    if fid_mod:
        marks = ",".join("?" * len(SLICE_EDGE_TYPES))
        for src, dst in con.execute(
            f"SELECT src_fid, dst_fid FROM edges WHERE type IN ({marks})",
            SLICE_EDGE_TYPES,
        ):
            a = fid_mod.get(src)
            b = fid_mod.get(dst)
            if a and b and a != b:
                cross[a] += 1
                cross[b] += 1
    migration_order = sorted(modules, key=lambda m: (cross[m["module_id"]], m["module_id"]))
    # 产物写出
    (out_dir / "shims").mkdir(parents=True, exist_ok=True)
    skeletons = shims = 0
    report_modules: list[dict] = []
    for m in migration_order:
        mid = m["module_id"]
        safe = _safe_id(mid)
        members = [
            {"fid": fid, "name": meta[fid][0], "label": meta[fid][1], "file": meta[fid][2]}
            for fid in sorted(m.get("symbol_fids", []))
            if fid in meta
        ]
        todo_lines = "\n".join(
            f"- {s['name']} ({s['label']}) <- {s['file']}" for s in members
        ) or "- (no resolvable symbols - check facts.db)"
        pkg_dir = out_dir / safe
        pkg_dir.mkdir(parents=True, exist_ok=True)
        init = pkg_dir / "__init__.py"
        init.write_text(
            _SKELETON.substitute(
                name=m.get("name", mid),
                responsibility=m.get("responsibility", ""),
                todo=todo_lines,
            ),
            encoding="utf-8",
            newline="\n",
        )
        skeletons += 1
        # shim 对：旧文件 × 新模块（Function/Class 可导出面；同文件多符号合一行）
        by_file: dict[str, list[str]] = {}
        for s in members:
            if s["label"] in SHIMMABLE_LABELS and s["file"] and s["name"]:
                by_file.setdefault(s["file"], []).append(s["name"])
        for old_file in sorted(by_file):
            # 文件名扁平化：只替换路径分隔符（保留 .py 等后缀可读性）
            flat = old_file.replace("\\", "/").replace("/", "_")
            shim_path = out_dir / "shims" / f"{flat}__to__{safe}.py"
            shim_path.write_text(
                _SHIM.substitute(
                    target_pkg=f"{out_dir.name}.{safe}",
                    imports=", ".join(sorted(set(by_file[old_file]))),
                ),
                encoding="utf-8",
                newline="\n",
            )
            shims += 1
        report_modules.append({
            "module_id": mid,
            "safe_name": safe,
            "cross_edges": cross[mid],
            "symbols": len(members),
            "files": len(by_file),
        })
    # MIGRATION.md：序+检查单（Fowler 先边缘后核心）
    md = ["# Strangler migration plan (D10, generated by `vrp scaffold`)", ""]
    md.append(f"Proposal: `{proposal_path}` — modules in migration order")
    md.append("(fewest cross-module edges first - edge modules before core, Fowler).")
    md.append("")
    for rm in report_modules:
        md.append(f"## {rm['module_id']} (`{rm['safe_name']}`) - {rm['cross_edges']} cross edges")
        md.append(f"- [ ] move {rm['symbols']} symbol(s) into `{rm['safe_name']}/`")
        md.append(f"- [ ] append shim re-exports ({rm['files']} file(s)) from `shims/`")
        md.append("- [ ] migrate callers to import from the new module")
        md.append("- [ ] delete shims once no caller imports the old path")
        md.append("")
    (out_dir / "MIGRATION.md").write_text("\n".join(md), encoding="utf-8", newline="\n")
    return {
        "repo": str(repo),
        "proposal": str(proposal_path),
        "out": str(out_dir),
        "modules": len(report_modules),
        "skeletons": skeletons,
        "shims": shims,
        "migration_order": report_modules,
        "note": "strangler scaffold draft - skeletons + shim templates + migration"
        " order (fewest cross edges first); adoption is manual (move files,"
        " append shims, migrate callers); Python first, other engines later",
    }


def render_text(result: dict) -> str:
    """人读呈现：迁移序（边缘→核心）+ 产物清单。"""
    lines = [f"vrp scaffold - {Path(result['repo']).name}"]
    lines.append(
        f"  {result['modules']} modules -> {result['skeletons']} skeleton(s),"
        f" {result['shims']} shim(s) at {Path(result['out'])}"
    )
    lines.append("  migration order (edge -> core):")
    for rm in result["migration_order"]:
        lines.append(
            f"    {rm['cross_edges']:>3} cross | {rm['symbols']:>3} syms | {rm['module_id']}"
        )
    return "\n".join(lines)
